// swift-tools-version: 6.4
import Foundation
import PackageDescription

// The Rust static library lives in the workspace's target directory. `swift build` and
// `swift test` both link target/app, where `scripts/rust-lib.sh` copies the release or app-dev
// build; run `scripts/build.sh` from the workspace root to produce it before building here.
let packageDir = URL(fileURLWithPath: #filePath).deletingLastPathComponent().path
let rustLibDir = packageDir + "/../target/app"

let package = Package(
    name: "RcGit",
    platforms: [.macOS("15.0")],
    targets: [
        // C ABI exported by crates/rc-git-ffi; header generated by scripts/gen-header.sh.
        .systemLibrary(name: "CRcGit", path: "Sources/CRcGit"),

        // Swift view of the core plus every piece of logic the app needs. No AppKit, so it
        // stays unit-testable.
        .target(
            name: "RcGitKit",
            dependencies: ["CRcGit"],
            path: "Sources/RcGitKit",
            linkerSettings: [
                .unsafeFlags(["-L", rustLibDir]),
                // The Rust side's HTTPS transport uses the system libcurl.
                .linkedLibrary("curl"),
                // The ssh transport's OpenSSH-config parsing resolves the local user
                // through SystemConfiguration.
                .linkedFramework("SystemConfiguration"),
            ]
        ),

        .executableTarget(
            name: "RcGitApp",
            dependencies: ["RcGitKit"],
            path: "Sources/RcGitApp"
        ),

        .testTarget(
            name: "RcGitKitTests",
            dependencies: ["RcGitKit"],
            path: "Tests/RcGitKitTests"
        ),
    ]
)
